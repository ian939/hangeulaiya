/* 한글 카드 앨범의 칸 순서와 회차별 자모 배정.
 *
 * 초성 자리의 자모와 받침 자리의 자모를 다른 칸으로 둔다.
 * 초성 ㄱ 을 아는 것과 받침 ㄱ 을 아는 것은 다른 지식이고,
 * 실제로 방송도 자음 단원(8~20화)과 받침 단원(21화~)을 나눠 가르친다.
 */
(function (AIYA) {
  'use strict';

  var VOWEL_BASIC = ['ㅏ', 'ㅑ', 'ㅓ', 'ㅕ', 'ㅗ', 'ㅛ', 'ㅜ', 'ㅠ', 'ㅡ', 'ㅣ'];
  var VOWEL_COMPLEX = ['ㅐ', 'ㅒ', 'ㅔ', 'ㅖ', 'ㅘ', 'ㅙ', 'ㅚ', 'ㅝ', 'ㅞ', 'ㅟ', 'ㅢ'];
  var CHO_BASIC = ['ㄱ', 'ㄴ', 'ㄷ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅅ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'];
  var CHO_DOUBLE = ['ㄲ', 'ㄸ', 'ㅃ', 'ㅆ', 'ㅉ'];
  var JONG_BASIC = ['ㄱ', 'ㄴ', 'ㄷ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅅ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'];
  var JONG_CLUSTER = ['ㄲ', 'ㅆ', 'ㄵ', 'ㄶ', 'ㄺ', 'ㄻ', 'ㄼ', 'ㄾ', 'ㅀ', 'ㅄ'];

  function batchim(list) {
    return list.map(function (j) { return '받침 ' + j; });
  }

  AIYA.data.cardOrder = VOWEL_BASIC
    .concat(VOWEL_COMPLEX)
    .concat(CHO_BASIC)
    .concat(CHO_DOUBLE)
    .concat(batchim(JONG_BASIC))
    .concat(batchim(JONG_CLUSTER));

  /* 회차별 자모 배정 — taught(N) 계산의 단일 출처.
   * 회차 설명란에 적힌 학습 목표를 그대로 옮겼다 (tools/crawl_youtube.py 로 확인).
   *
   * ㅇ 에 주의: 8~20화의 자음 단원은 가수·나비·두유·라디오·모자·버스·소리·
   * 자유·차·코·토마토·피자·휴지 = 자음 13개이고 **ㅇ 은 자기 회차가 없다**.
   * ㅇ 은 1화 '아이야' 부터 모음의 자리를 지키는 무음 글자로 계속 나오고,
   * 받침 ㅇ 은 28화 '공' 에서 처음 정식으로 배운다.
   * 그래서 초성 ㅇ 을 1화에 넣어 둔다. 이게 방송의 실제 구조다.
   *
   * 단원 순서가 회차 번호와 어긋나는 구간이 있다. 방송 편성이 그렇다.
   *   21~34화 기본 받침 → 35~39화 쌍자음 → 40~50화 복잡한 모음
   *   → 51~60화 다시 받침(겹받침)
   */
  AIYA.data.curriculum = {
    // 기본 모음
    1: ['ㅏ', 'ㅣ', 'ㅑ', 'ㅇ'], 2: ['ㅗ'], 3: ['ㅓ'], 4: ['ㅕ', 'ㅜ'], 5: ['ㅠ'],
    6: ['ㅛ'], 7: ['ㅡ'],
    // 기본 자음
    8: ['ㄱ'], 9: ['ㄴ'], 10: ['ㄷ'], 11: ['ㄹ'], 12: ['ㅁ'], 13: ['ㅂ'],
    14: ['ㅅ'], 15: ['ㅈ'], 16: ['ㅊ'], 17: ['ㅋ'], 18: ['ㅌ'], 19: ['ㅍ'], 20: ['ㅎ'],
    // 기본 받침
    21: ['받침 ㄱ'], 22: ['받침 ㄴ'], 23: ['받침 ㄷ'], 24: ['받침 ㄹ'], 25: ['받침 ㅁ'],
    26: ['받침 ㅂ'], 27: ['받침 ㅅ'], 28: ['받침 ㅇ'], 29: ['받침 ㅈ'], 30: ['받침 ㅊ'],
    31: ['받침 ㅋ'], 32: ['받침 ㅌ'], 33: ['받침 ㅍ'], 34: ['받침 ㅎ'],
    // 쌍자음
    35: ['ㄲ'], 36: ['ㄸ'], 37: ['ㅃ'], 38: ['ㅆ'], 39: ['ㅉ'],
    // 복잡한 모음
    40: ['ㅐ'], 41: ['ㅒ'], 42: ['ㅔ'], 43: ['ㅖ'], 44: ['ㅘ'], 45: ['ㅙ'],
    46: ['ㅚ'], 47: ['ㅝ'], 48: ['ㅞ'], 49: ['ㅟ'], 50: ['ㅢ'],
    // 겹받침
    51: ['받침 ㄲ'], 52: ['받침 ㅆ'], 53: ['받침 ㄵ'], 54: ['받침 ㄶ'], 55: ['받침 ㄺ'],
    56: ['받침 ㄻ'], 57: ['받침 ㄼ'], 58: ['받침 ㄾ'], 59: ['받침 ㅀ'], 60: ['받침 ㅄ']
  };

  /** N화 시작 시점에 이미 배운 카드들. */
  AIYA.data.taught = function (n) {
    var out = [];
    Object.keys(AIYA.data.curriculum).forEach(function (k) {
      if (parseInt(k, 10) < n) out = out.concat(AIYA.data.curriculum[k]);
    });
    return out;
  };
})(window.AIYA);
