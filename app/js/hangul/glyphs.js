/* 자모의 획 데이터 (중심선).
 *
 * 좌표계: 자모 자신의 단위 상자 [0,1] x [0,1], y 는 아래로 증가.
 * 이 상자를 layout.js 가 음절 안의 작은 칸에 앉힌다. 그래서 자모 40개 분량,
 * 폴리라인 90개 정도만 있으면 11,172자를 전부 만들 수 있다.
 *
 * ── 획수·순서의 근거 ─────────────────────────────────────────
 * 한글 자모의 필순에는 국가가 고시한 공식 규정이 없다. 「한글 맞춤법」은 자모의
 * 수·순서·이름만 정하고 획순은 다루지 않는다. 여기 데이터는 초등 국어 교과서에
 * 제시된 관행(사실상의 표준)을 따랐다.
 *
 * 핵심 관행: **꺾임은 한 획으로 센다** (한자 乙·口 의 계산법과 같다).
 *   따라서 ㄱ ㄴ ㅇ = 1획, ㄷ ㅅ ㅈ ㅋ = 2획, ㄹ ㅁ ㅊ ㅌ ㅎ = 3획, ㅂ ㅍ = 4획.
 *   영어권 학습 사이트들이 꺾임을 분해해 세면서 ㄹ을 5획이라고 하는 것과 다르다.
 *
 * 원칙: 위→아래, 왼쪽→오른쪽, 가로획 먼저. 단 ㅏ·ㅑ 는 기둥(주된 획)을 먼저 쓴다.
 *
 * closed:true 인 획(ㅇ, ㅎ의 동그라미)은 방향을 채점하지 않는다.
 * 시계/반시계 중 무엇이 표준인지 정한 문서가 없어서, 아이에게 방향을 강요하지 않는다.
 *
 * 위치(초성/종성)에 따라 자형은 달라지지만 **획의 수와 순서는 같다**.
 * 크기·비율 변화는 layout.js 의 상자가 처리한다.
 */
