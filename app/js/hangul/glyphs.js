  /** 원을 폴리라인으로. dir=1 이면 시계 방향(y 아래 좌표계 기준). */
  function circle(cx, cy, r, dir, n) {
    n = n || 20;
    dir = dir === undefined ? 1 : dir;
    var pts = [];
    for (var i = 0; i <= n; i++) {
      var t = (i / n) * Math.PI * 2 * dir - Math.PI / 2; // 12시에서 시작
      pts.push([cx + r * Math.cos(t), cy + r * Math.sin(t)]);
    }
    return pts;
  }

  function s(pts, dir, closed) {
    return { pts: pts, dir: dir || '', closed: !!closed };
  }

